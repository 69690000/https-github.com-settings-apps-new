export const REGIONS = [
  { key: 'America', prefix: 'us' },
  { key: 'Europe', prefix: 'eu' },
  { key: 'Southeast Asia', prefix: 'sg' },
];

export function serversFor(symbol) {
  const lower = symbol.toLowerCase();
  return REGIONS.map((region, index) => ({
    region: region.key,
    host: `${region.prefix}.${lower}.ss.cloverpool.com`,
    port: 1800,
    priority: index + 1,
  }));
}

export const UNIT_FACTOR = { H: 1, K: 1e3, M: 1e6, G: 1e9, T: 1e12, P: 1e15, E: 1e18 };

/** USD earned per day for one hash per second on this coin's pool. */
export function usdPerHashPerDay(coin) {
  const unit = String(coin.revenueUnit || 'TH').replace(/H$/, '');
  return coin.revenueUsdPerDay / (UNIT_FACTOR[unit] || 1e12);
}
